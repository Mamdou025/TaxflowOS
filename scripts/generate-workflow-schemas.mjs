import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';

// The persisted domain types are the source of truth. Generate runtime validators
// from that closed, JSON-shaped contract rather than hand-copying its fields.
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, 'lib/workflow-contracts/src');
const entry = path.join(source, 'library-types.ts');
const program = ts.createProgram([entry], {
  strict: true,
  target: ts.ScriptTarget.ES2022,
  moduleResolution: ts.ModuleResolutionKind.Bundler,
  module: ts.ModuleKind.ESNext,
  types: [],
});
const checker = program.getTypeChecker();
const diagnostics = ts.getPreEmitDiagnostics(program);
if (diagnostics.length) {
  throw new Error(
    ts.formatDiagnosticsWithColorAndContext(diagnostics, {
      getCanonicalFileName: (file) => file,
      getCurrentDirectory: () => root,
      getNewLine: () => '\n',
    }),
  );
}

const named = new Map();
for (const file of program.getSourceFiles()) {
  if (!file.fileName.replaceAll('\\', '/').startsWith(source.replaceAll('\\', '/'))) continue;
  for (const node of file.statements) {
    if (!ts.isTypeAliasDeclaration(node)) continue;
    const type = checker.getTypeAtLocation(node.name);
    named.set(type, {
      name: node.name.text,
      module:
        './' + path.relative(source, file.fileName).replaceAll('\\', '/').replace(/\.ts$/, ''),
    });
  }
}

const pending = new Map();
function reference(type) {
  const info = named.get(type);
  if (!info) return schema(type);
  pending.set(type, info);
  return `${info.name}Schema`;
}
function schema(type) {
  if (type.flags & ts.TypeFlags.StringLiteral) return `z.literal(${JSON.stringify(type.value)})`;
  if (type.flags & ts.TypeFlags.NumberLiteral) return `z.literal(${type.value})`;
  if (type.flags & ts.TypeFlags.BooleanLiteral) return `z.literal(${type.intrinsicName})`;
  if (type.flags & ts.TypeFlags.String) return 'z.string()';
  if (type.flags & ts.TypeFlags.Number) return 'z.number().finite()';
  if (type.flags & ts.TypeFlags.Boolean) return 'z.boolean()';
  if (type.flags & ts.TypeFlags.Null) return 'z.null()';
  if (type.flags & ts.TypeFlags.Undefined) return 'z.undefined()';
  if (type.flags & ts.TypeFlags.Unknown) return 'z.unknown()';
  if (type.flags & ts.TypeFlags.Any)
    throw new Error('Explicit any is forbidden in persisted contracts.');
  if (type.isUnion()) {
    return `z.union([${type.types.map(reference).join(', ')}])`;
  }
  if (checker.isArrayType(type)) return `z.array(${reference(checker.getTypeArguments(type)[0])})`;
  if (type.getSymbol()?.name === 'Date') return 'storedDate';
  if (type.getCallSignatures().length) throw new Error('Functions cannot be persisted.');
  const index = type.getStringIndexType();
  if (index) return `z.record(${reference(index)})`;
  if (!(type.flags & ts.TypeFlags.Object)) {
    throw new Error(`Unsupported persisted type: ${checker.typeToString(type)}`);
  }
  const fields = checker.getPropertiesOfType(type).map((property) => {
    const declaration = property.valueDeclaration ?? property.declarations?.[0];
    const propertyType = checker.getTypeOfSymbolAtLocation(property, declaration);
    const optional = Boolean(property.flags & ts.SymbolFlags.Optional);
    // Remove the implicit undefined before applying optional(), so required
    // nullable values stay required and the output type matches the contract.
    const parts =
      optional && propertyType.isUnion()
        ? propertyType.types.filter((part) => !(part.flags & ts.TypeFlags.Undefined))
        : [propertyType];
    const value =
      parts.length === 1 ? reference(parts[0]) : `z.union([${parts.map(reference).join(', ')}])`;
    return `  ${JSON.stringify(property.name)}: ${value}${optional ? '.optional()' : ''},`;
  });
  return `z.object({\n${fields.join('\n')}\n}).passthrough()`;
}

const rootType = [...named].find(([, info]) => info.name === 'WorkflowLibrary')?.[0];
if (!rootType) throw new Error('WorkflowLibrary contract not found.');
reference(rootType);
const declarations = [];
for (const [type, info] of pending) {
  const validator = schema(type);
  const migrated =
    info.name === 'WorkflowRelationshipType'
      ? `z.preprocess(migrateWorkflowRelationship, ${validator})`
      : validator;
  declarations.push(
    `export const ${info.name}Schema: z.ZodType<import(${JSON.stringify(info.module)}).${info.name}, z.ZodTypeDef, unknown> = z.lazy(() => ${migrated});`,
  );
}
const output = [
  '// Generated by scripts/generate-workflow-schemas.mjs. Do not edit manually.',
  "import { z } from 'zod';",
  "import { migrateWorkflowRelationship } from './migrations';",
  '// Storage serializes Date values as ISO strings; restore valid dates on read.',
  'const storedDate = z.union([z.date(), z.string().datetime({ offset: true }).transform(value => new Date(value))]);',
  ...declarations,
  '',
].join('\n\n');
const destination = path.join(source, 'generated-schemas.ts');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) {
    throw new Error('Workflow schemas are stale. Run pnpm run contracts:generate.');
  }
  console.log('Workflow runtime schemas match the domain contracts.');
} else {
  fs.writeFileSync(destination, output);
  console.log(`Generated ${declarations.length} workflow contract validators.`);
}
