import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildIndex, hash } from './indexer.mjs';

const directory = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(directory, '../..');
const output = path.join(root, '.archify');
const contentFile = path.join(directory, 'content.json');
const outputs = [
  ['viewer.html', 'index.html'],
  ['viewer.css', 'explorer.css'],
  ['viewer.js', 'explorer.js'],
];
const prefix = 'globalThis.TAXFLOW_ARCHITECTURE = ';
const check = process.argv.includes('--check');
const watch = process.argv.includes('--watch');
if (
  process.argv.slice(2).some((argument) => !['--check', '--watch'].includes(argument)) ||
  (check && watch)
) {
  throw new Error('Usage: node scripts/architecture-explorer/build.mjs [--check | --watch]');
}

function run() {
  const content = JSON.parse(fs.readFileSync(contentFile, 'utf8'));
  const dataFile = path.join(output, 'explorer-data.js');
  let previous;
  if (fs.existsSync(dataFile)) {
    const saved = fs.readFileSync(dataFile, 'utf8');
    if (saved.startsWith(prefix)) {
      try {
        previous = JSON.parse(saved.slice(prefix.length).trim().replace(/;$/, ''));
      } catch {
        /* Rebuild an invalid generated file. */
      }
    }
  }
  const data = buildIndex({ root, content, generatedAt: previous?.meta.generatedAt });
  const templates = outputs.map(([source, destination]) => ({
    source,
    destination,
    bytes: fs.readFileSync(path.join(directory, source)),
  }));
  data.meta.inputHash = hash(
    data.meta.inputHash +
      hash(fs.readFileSync(path.join(directory, 'indexer.mjs'))) +
      hash(fs.readFileSync(fileURLToPath(import.meta.url))) +
      templates.map((entry) => hash(entry.bytes)).join(''),
  );
  if (!previous || previous.meta.inputHash !== data.meta.inputHash)
    data.meta.generatedAt = new Date().toISOString();
  const serialize = (value) =>
    prefix +
    JSON.stringify(value)
      .replaceAll('<', '\\u003c')
      .replaceAll('\u2028', '\\u2028')
      .replaceAll('\u2029', '\\u2029') +
    ';\n';
  const javascript = serialize(data);
  const stale = [];
  if (!fs.existsSync(dataFile) || fs.readFileSync(dataFile, 'utf8') !== javascript)
    stale.push('explorer-data.js');
  for (const entry of templates) {
    const destination = path.join(output, entry.destination);
    if (!fs.existsSync(destination) || !fs.readFileSync(destination).equals(entry.bytes))
      stale.push(entry.destination);
  }
  if (check && stale.length)
    throw new Error(
      `Architecture explorer is stale: ${stale.join(', ')}. Run pnpm run explorer:build.`,
    );
  if (!check) {
    fs.mkdirSync(output, { recursive: true });
    if (stale.includes('explorer-data.js')) {
      const temporary = dataFile + '.tmp';
      fs.writeFileSync(temporary, javascript);
      fs.renameSync(temporary, dataFile);
    }
    for (const entry of templates)
      if (stale.includes(entry.destination))
        fs.writeFileSync(path.join(output, entry.destination), entry.bytes);
  }
  console.log(
    `${check ? 'Current' : stale.length ? 'Built' : 'Unchanged'} architecture explorer: ${data.meta.counts.files} files, ${data.meta.counts.resolvedImports} resolved import references, ${data.meta.counts.reviewedFiles} reviewed explanations (${data.meta.counts.staleReviews} need review).`,
  );
}

run();
if (watch) {
  console.log(
    'Watching source and configuration. Refresh the browser after a rebuild. Ctrl+C stops watching. Semantic explanations are never regenerated by AI automatically.',
  );
  let timeout;
  const watcher = fs.watch(root, { recursive: true }, (_, filename) => {
    const file = String(filename || '').replaceAll('\\', '/');
    if (
      /(?:^|\/)(?:\.archify|node_modules|\.next|dist|coverage|test-results|playwright-report|attached_assets|archive)(?:\/|$)/.test(
        file,
      )
    )
      return;
    if (file.startsWith('.git/') && !/(?:^|\/)(?:HEAD|index|refs\/heads\/[^/]+)$/.test(file))
      return;
    clearTimeout(timeout);
    timeout = setTimeout(() => {
      try {
        run();
      } catch (error) {
        console.error(`Explorer refresh failed; previous output retained. ${error.message}`);
      }
    }, 650);
  });
  process.on('SIGINT', () => {
    clearTimeout(timeout);
    watcher.close();
    process.exit(0);
  });
}
